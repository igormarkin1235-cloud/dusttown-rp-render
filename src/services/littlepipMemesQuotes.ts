export function findMatchingMemeQuote(userText: string): MemeQuote | null {
  const lower = userText.toLowerCase();
  for (const item of POPULAR_MEME_QUOTES) {
    if (item.triggerKeywords.some(kw => lower.includes(kw))) {
      return item;
    }
  }
  return null;
}

export function getRandomAnecdote(): string {
  return WASTELAND_ANECDOTES[Math.floor(Math.random() * WASTELAND_ANECDOTES.length)];
}

export function getMemeQuotesPromptGuidance(userText: string): string {
  const match = findMatchingMemeQuote(userText);
  let guidance = `ЗНАНИЕ ИНТЕРНЕТ-МЕМОВ И АНЕКДОТОВ:
Ты органично чувствуешь постиронию, интернет-мемы, геймерский сленг и сталкерский фольклор.
Можешь к месту ввернуть или перефразировать культовую цитату («Это не баг, это фича», «Press F», «Шо, опять?!», «Слабоумие и отвага», «Карл!», «И так сойдёт», «Не лезь, оно тебя сожрёт»).`;

  if (match) {
    guidance += `\n[ПОДСКАЗКА ПО МЕМУ]: К текущей реплике отлично подходит мотив: "${match.quote}". Можешь обыграть или процитировать его в ответе!`;
  }

  return guidance;
}
